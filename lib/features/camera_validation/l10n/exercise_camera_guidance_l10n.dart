abstract final class ExerciseCameraGuidanceL10n {
  static bool _isRu(AppLocalizations l10n) => l10n.localeName.startsWith('ru');

  static CameraGuidance localized(AppLocalizations l10n, ExerciseProfile profile) {
    if (!_isRu(l10n)) return profile.guidance;
    final ru = _ruById[profile.id];
    if (ru == null) return profile.guidance;
    return CameraGuidance(
      orientation: profile.orientationHint,
      framingHint: ru.framing,
      safetyNote: ru.safety,
      placementHint: ru.placement,
      setupSteps: ru.steps,
    );
  }

  static String orientationLabel(AppLocalizations l10n, CameraOrientationHint hint) {
    if (!_isRu(l10n)) {
      return switch (hint) {
        CameraOrientationHint.front => 'Front view',
        CameraOrientationHint.side => 'Side view',
        CameraOrientationHint.any => 'Flexible angle',
      };
    }
    return switch (hint) {
      CameraOrientationHint.front => 'Вид спереди',
      CameraOrientationHint.side => 'Вид сбоку',
      CameraOrientationHint.any => 'Любой удобный ракурс',
    };
  }
}

